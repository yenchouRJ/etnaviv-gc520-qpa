/* -----------------------------------------------------------------------
 * Construction / destruction
 * ----------------------------------------------------------------------- */
QEtnaviv2dWaylandTransport::QEtnaviv2dWaylandTransport(etna2d_device *etnaDev,
                                                       int            cardFd,
                                                       QObject       *parent)
    : QObject(parent)
    , m_etnadev(etnaDev)
    , m_cardFd(cardFd)
{
}

QEtnaviv2dWaylandTransport::~QEtnaviv2dWaylandTransport()
{
    disconnect();
}

/* -----------------------------------------------------------------------
 * connect() — bind Wayland globals, create xdg_toplevel, wait for configure
 * ----------------------------------------------------------------------- */
bool QEtnaviv2dWaylandTransport::connect()
{
    /* 1. Open display */
    m_display = wl_display_connect(nullptr);
    if (!m_display) {
        WL_WARN << "wl_display_connect failed — is WAYLAND_DISPLAY set?";
        return false;
    }
    WL_INFO << "Connected to Wayland display";

    /* 2. Registry — bind compositor, xdg_wm_base, linux_dmabuf */
    m_registry = wl_display_get_registry(m_display);
    static const wl_registry_listener reg_listener = {
        registryGlobal,
        registryGlobalRemove
    };
    wl_registry_add_listener(m_registry, &reg_listener, this);

    /* Roundtrip 1: receive all globals */
    wl_display_roundtrip(m_display);

    if (!m_compositor || !m_xdgWmBase || !m_dmabuf) {
        WL_WARN << "Required Wayland globals missing:"
                << "compositor=" << (m_compositor ? "ok" : "MISSING")
                << "xdg_wm_base=" << (m_xdgWmBase ? "ok" : "MISSING")
                << "linux_dmabuf=" << (m_dmabuf ? "ok" : "MISSING");
        disconnect();
        return false;
    }

    /* 3. Create wl_surface + xdg_surface + xdg_toplevel */
    m_surface = wl_compositor_create_surface(m_compositor);

    m_xdgSurface = xdg_wm_base_get_xdg_surface(m_xdgWmBase, m_surface);
    static const xdg_surface_listener surf_listener = {
        xdgSurfaceConfigure
    };
    xdg_surface_add_listener(m_xdgSurface, &surf_listener, this);

    m_xdgToplevel = xdg_surface_get_toplevel(m_xdgSurface);
    static const xdg_toplevel_listener tl_listener = {
        xdgToplevelConfigure,
        xdgToplevelClose,
        nullptr, /* configure_bounds (informational, ignored) */
        nullptr, /* wm_capabilities  (informational, ignored) */
    };
    xdg_toplevel_add_listener(m_xdgToplevel, &tl_listener, this);

    xdg_toplevel_set_title(m_xdgToplevel, "etnaviv2d-qt");
    xdg_toplevel_set_fullscreen(m_xdgToplevel, nullptr); /* any output */

    /* Initial commit to trigger the configure event */
    wl_surface_commit(m_surface);

    /* 4. Pump until xdg_surface configure arrives (the geometry roundtrip).
     * We pump synchronously here because the integration's initialize() needs
     * the output geometry before returning.  This is a one-time startup cost. */
    int timeout = 200; /* max 200 roundtrips (~20 ms) */
    while (!m_configured && timeout-- > 0)
        wl_display_roundtrip(m_display);

    if (!m_configured) {
        WL_WARN << "Timed out waiting for xdg_surface configure";
        disconnect();
        return false;
    }

    WL_INFO << "xdg_toplevel configured, output geometry ="
            << m_outputGeometry.width() << "x" << m_outputGeometry.height();

    /* 5. Wire QSocketNotifier for all subsequent event delivery.
     *
     * NOTE: the notifier must NOT be created here during initializeHardware()
     * because QApplication has not yet started its event loop.  Creating a
     * QSocketNotifier before the event loop is running produces the warning
     * "Can only be used with threads started with QThread" and silently
     * disables it — wl_buffer.release events never arrive, the ring never
     * drains, and the frame-callback chain stalls.
     *
     * Instead, defer notifier creation to the first call to commitFrame()
     * (which happens after QApplication::exec() enters the event loop).
     * The same applies to the aboutToBlock connection.
     * See armNotifier() which is called lazily from commitFrame(). */

    m_connected = true;
    return true;
}

/* -----------------------------------------------------------------------
 * allocateRing() — allocate 3 ARGB8888/LINEAR BOs and export as wl_buffers
 * ----------------------------------------------------------------------- */
bool QEtnaviv2dWaylandTransport::allocateRing()
{
    if (!m_configured) {
        WL_WARN << "allocateRing: not yet configured";
        return false;
    }

    const int w = m_outputGeometry.width();
    const int h = m_outputGeometry.height();

    for (int i = 0; i < WL_RING_SIZE; ++i) {
        ArgbBo &slot = m_ring[i];

        /* Allocate dumb BO on card fd.
         * We use a dumb BO (not etna2d_surface_create) so we can PRIME-export it
         * as a dmabuf for Weston, then import it back into etnaviv for blitting.
         * This mirrors the KMS scanout BO path in qetnaviv2dscreen.cpp. */
        struct drm_mode_create_dumb creq = {};
        creq.width  = (uint32_t)w;
        creq.height = (uint32_t)h;
        creq.bpp    = 32;
        if (drmIoctl(m_cardFd, DRM_IOCTL_MODE_CREATE_DUMB, &creq)) {
            WL_WARN << "ring[" << i << "] CREATE_DUMB:" << strerror(errno);
            return false;
        }

        /* PRIME-export the dumb BO as a dmabuf fd */
        if (drmPrimeHandleToFD(m_cardFd, creq.handle,
                               DRM_CLOEXEC | DRM_RDWR, &slot.dmabuf_fd)) {
            WL_WARN << "ring[" << i << "] PRIME export:" << strerror(errno);
            struct drm_mode_destroy_dumb dreq = { .handle = creq.handle };
            drmIoctl(m_cardFd, DRM_IOCTL_MODE_DESTROY_DUMB, &dreq);
            return false;
        }

        /* Destroy the GEM handle — the dmabuf fd keeps the BO alive */
        {
            struct drm_mode_destroy_dumb dreq = { .handle = creq.handle };
            drmIoctl(m_cardFd, DRM_IOCTL_MODE_DESTROY_DUMB, &dreq);
        }

        /* Import into etnaviv so the GC520 DE can render into it */
        if (etna2d_surface_from_dmabuf(m_etnadev, slot.dmabuf_fd,
                                        w, h, creq.pitch,
                                        &slot.surf) != ETNA2D_OK
                || !slot.surf) {
            WL_WARN << "ring[" << i << "] etna2d_surface_from_dmabuf failed";
            close(slot.dmabuf_fd);
            slot.dmabuf_fd = -1;
            return false;
        }

        /* Create persistent wl_buffer via zwp_linux_dmabuf_v1 */
        zwp_linux_buffer_params_v1 *params =
            zwp_linux_dmabuf_v1_create_params(m_dmabuf);

        /* We need a fresh fd per params (kernel closes it after import) */
        int fd_dup = dup(slot.dmabuf_fd);
        if (fd_dup < 0) {
            WL_WARN << "ring[" << i << "] dup(dmabuf_fd):" << strerror(errno);
            etna2d_surface_destroy(slot.surf); slot.surf = nullptr;
            close(slot.dmabuf_fd); slot.dmabuf_fd = -1;
            zwp_linux_buffer_params_v1_destroy(params);
            return false;
        }

        zwp_linux_buffer_params_v1_add(params, fd_dup,
                                       0,               /* plane index */
                                       0,               /* offset */
                                       creq.pitch,
                                       DRM_FORMAT_MOD_LINEAR >> 32,
                                       DRM_FORMAT_MOD_LINEAR & 0xffffffff);

        /* Use create_immed (synchronous) — avoids an extra roundtrip */
        slot.wl_buf = zwp_linux_buffer_params_v1_create_immed(
                          params,
                          w, h,
                          DRM_FORMAT_ARGB8888,
                          0 /* flags */);
        zwp_linux_buffer_params_v1_destroy(params);
        close(fd_dup);

        if (!slot.wl_buf) {
            WL_WARN << "ring[" << i << "] zwp_linux_buffer_params create_immed failed";
            etna2d_surface_destroy(slot.surf); slot.surf = nullptr;
            close(slot.dmabuf_fd); slot.dmabuf_fd = -1;
            return false;
        }

        /* Wire the release callback so the ring back-pressure works */
        static const wl_buffer_listener buf_listener = { bufferRelease };
        wl_buffer_add_listener(slot.wl_buf, &buf_listener, &slot);

        slot.in_use.store(false);
        WL_DBG << "ring[" << i << "] surf=" << slot.surf
               << "dmabuf_fd=" << slot.dmabuf_fd
               << "wl_buf=" << slot.wl_buf;
    }

    WL_INFO << "ARGB ring allocated:" << WL_RING_SIZE << "x"
            << w << "x" << h << "ARGB8888/LINEAR";
    return true;
}

/* -----------------------------------------------------------------------
 * currentBo() — return the ring slot the blitter should render into
 * ----------------------------------------------------------------------- */
etna2d_surface *QEtnaviv2dWaylandTransport::currentBo()
{
    int slot = pickFree();
    if (slot < 0) {
        WL_WARN << "currentBo: all ring slots in use (back-pressure)";
        return nullptr;
    }
    m_currentSlot = slot;
    return m_ring[slot].surf;
}

/* -----------------------------------------------------------------------
 * armNotifier() — create QSocketNotifier lazily on first commitFrame().
 * Called after QApplication::exec() has entered the event loop so the
 * notifier is guaranteed to be associated with a running QThread.
 * ----------------------------------------------------------------------- */
void QEtnaviv2dWaylandTransport::armNotifier()
{
    if (m_notifier)
        return; /* already armed */

    m_notifier = new QSocketNotifier(wl_display_get_fd(m_display),
                                     QSocketNotifier::Read, this);
    QObject::connect(m_notifier, &QSocketNotifier::activated,
                     this, &QEtnaviv2dWaylandTransport::onWaylandReadable);

    /* Flush pending writes to compositor on every event-loop idle */
    if (QAbstractEventDispatcher *ed = QAbstractEventDispatcher::instance()) {
        QObject::connect(ed, &QAbstractEventDispatcher::aboutToBlock,
                         this, &QEtnaviv2dWaylandTransport::onAboutToBlock);
    }

    WL_DBG << "QSocketNotifier armed on fd" << wl_display_get_fd(m_display);
}

/* -----------------------------------------------------------------------
 * commitFrame() — called from BackingStore::flush() after blitting
 * ----------------------------------------------------------------------- */
void QEtnaviv2dWaylandTransport::commitFrame(etna2d_surface *bo)
{
    /* Arm the QSocketNotifier lazily on first commit — by this point
     * QApplication::exec() is running and the notifier will work correctly. */
    armNotifier();
    /* Find which slot was rendered into */
    int slot = -1;
    for (int i = 0; i < WL_RING_SIZE; ++i) {
        if (m_ring[i].surf == bo) { slot = i; break; }
    }
    if (slot < 0) {
        WL_WARN << "commitFrame: unknown BO surface pointer";
        return;
    }

    m_pendingCommitSlot = slot;
    m_dirty = true;

    if (!m_frameCallback) {
        /* No frame callback pending — first frame or compositor is idle.
         * Commit immediately to bootstrap the frame-callback chain. */
        doCommit(slot);
    }
    /* else: frame callback already armed; doCommit will be called when it fires */
}

/* -----------------------------------------------------------------------
 * doCommit() — attach + damage + commit, arm next frame callback
 * ----------------------------------------------------------------------- */
void QEtnaviv2dWaylandTransport::doCommit(int slot)
{
    ArgbBo &bo = m_ring[slot];
    bo.in_use.store(true);

    wl_surface_attach(m_surface, bo.wl_buf, 0, 0);
    wl_surface_damage_buffer(m_surface, 0, 0,
                              m_outputGeometry.width(),
                              m_outputGeometry.height());

    armFrameCallback();
    wl_surface_commit(m_surface);
    wl_display_flush(m_display);

    m_dirty = false;
    m_pendingCommitSlot = -1;

    WL_DBG << "committed slot" << slot;
}

/* -----------------------------------------------------------------------
 * armFrameCallback() — request wl_surface.frame for the next vblank
 * ----------------------------------------------------------------------- */
void QEtnaviv2dWaylandTransport::armFrameCallback()
{
    if (m_frameCallback)
        wl_callback_destroy(m_frameCallback);

    m_frameCallback = wl_surface_frame(m_surface);
    static const wl_callback_listener frame_listener = { frameCallback };
    wl_callback_add_listener(m_frameCallback, &frame_listener, this);
}

/* -----------------------------------------------------------------------
 * pickFree() — return first non-in_use slot
 * ----------------------------------------------------------------------- */
int QEtnaviv2dWaylandTransport::pickFree() const
{
    /* Prefer the slot after the current one (round-robin) */
    for (int i = 0; i < WL_RING_SIZE; ++i) {
        int s = (m_currentSlot + 1 + i) % WL_RING_SIZE;
        if (!m_ring[s].in_use.load())
            return s;
    }
    return -1;
}

/* -----------------------------------------------------------------------
 * disconnect() — release all Wayland + BO resources
 * ----------------------------------------------------------------------- */
void QEtnaviv2dWaylandTransport::disconnect()
{
    m_connected = false;

    delete m_notifier;
    m_notifier = nullptr;

    if (m_frameCallback) {
        wl_callback_destroy(m_frameCallback);
        m_frameCallback = nullptr;
    }

    /* Free ring BOs */
    for (int i = 0; i < WL_RING_SIZE; ++i) {
        ArgbBo &slot = m_ring[i];
        if (slot.wl_buf) { wl_buffer_destroy(slot.wl_buf); slot.wl_buf = nullptr; }
        if (slot.surf)   { etna2d_surface_destroy(slot.surf); slot.surf = nullptr; }
        if (slot.dmabuf_fd >= 0) { close(slot.dmabuf_fd); slot.dmabuf_fd = -1; }
        slot.in_use.store(false);
    }

    if (m_xdgToplevel) { xdg_toplevel_destroy(m_xdgToplevel); m_xdgToplevel = nullptr; }
    if (m_xdgSurface)  { xdg_surface_destroy(m_xdgSurface);   m_xdgSurface  = nullptr; }
    if (m_surface)     { wl_surface_destroy(m_surface);        m_surface     = nullptr; }
    if (m_dmabuf)      { zwp_linux_dmabuf_v1_destroy(m_dmabuf); m_dmabuf     = nullptr; }
    if (m_xdgWmBase)   { xdg_wm_base_destroy(m_xdgWmBase);    m_xdgWmBase   = nullptr; }
    if (m_compositor)  { wl_compositor_destroy(m_compositor);  m_compositor  = nullptr; }
    if (m_registry)    { wl_registry_destroy(m_registry);      m_registry    = nullptr; }
    if (m_display)     { wl_display_disconnect(m_display);     m_display     = nullptr; }
}

/* -----------------------------------------------------------------------
 * QSocketNotifier slot — safe Wayland read/dispatch sequence
 * ----------------------------------------------------------------------- */
void QEtnaviv2dWaylandTransport::onWaylandReadable()
{
    /* prepare_read / read_events / dispatch_pending avoids the classic
     * fd-starvation deadlock where poll() returns readable but another thread
     * already consumed the data via dispatch(). */
    if (wl_display_prepare_read(m_display) == 0) {
        wl_display_read_events(m_display);
    }
    wl_display_dispatch_pending(m_display);
    wl_display_flush(m_display);
}

/* -----------------------------------------------------------------------
 * aboutToBlock slot — flush pending writes to compositor
 * ----------------------------------------------------------------------- */
void QEtnaviv2dWaylandTransport::onAboutToBlock()
{
    if (m_display)
        wl_display_flush(m_display);
}

/* -----------------------------------------------------------------------
 * wl_registry listeners
 * ----------------------------------------------------------------------- */
void QEtnaviv2dWaylandTransport::registryGlobal(void *data,
                                                 wl_registry *reg,
                                                 uint32_t name,
                                                 const char *iface,
                                                 uint32_t version)
{
    auto *self = static_cast<QEtnaviv2dWaylandTransport *>(data);

    if (strcmp(iface, wl_compositor_interface.name) == 0) {
        self->m_compositor = static_cast<wl_compositor *>(
            wl_registry_bind(reg, name, &wl_compositor_interface,
                             qMin(version, 4u)));
    } else if (strcmp(iface, xdg_wm_base_interface.name) == 0) {
        self->m_xdgWmBase = static_cast<xdg_wm_base *>(
            wl_registry_bind(reg, name, &xdg_wm_base_interface,
                             qMin(version, 2u)));
        static const xdg_wm_base_listener wm_listener = { xdgWmBasePing };
        xdg_wm_base_add_listener(self->m_xdgWmBase, &wm_listener, self);
    } else if (strcmp(iface, zwp_linux_dmabuf_v1_interface.name) == 0) {
        self->m_dmabuf = static_cast<zwp_linux_dmabuf_v1 *>(
            wl_registry_bind(reg, name, &zwp_linux_dmabuf_v1_interface,
                             qMin(version, 3u)));
        static const zwp_linux_dmabuf_v1_listener dmabuf_listener = {
            dmabufFormat, dmabufModifier
        };
        zwp_linux_dmabuf_v1_add_listener(self->m_dmabuf, &dmabuf_listener, self);
    }
}

void QEtnaviv2dWaylandTransport::registryGlobalRemove(void * /*data*/,
                                                       wl_registry * /*reg*/,
                                                       uint32_t /*name*/)
{
    /* Globals disappearing at runtime is unexpected for a kiosk compositor. */
}

/* -----------------------------------------------------------------------
 * xdg_wm_base ping — must respond to keep the surface alive
 * ----------------------------------------------------------------------- */
void QEtnaviv2dWaylandTransport::xdgWmBasePing(void * /*data*/,
                                                xdg_wm_base *base,
                                                uint32_t serial)
{
    xdg_wm_base_pong(base, serial);
}

/* -----------------------------------------------------------------------
 * xdg_surface configure — acknowledge and record geometry
 * ----------------------------------------------------------------------- */
void QEtnaviv2dWaylandTransport::xdgSurfaceConfigure(void *data,
                                                      xdg_surface *surf,
                                                      uint32_t serial)
{
    auto *self = static_cast<QEtnaviv2dWaylandTransport *>(data);
    xdg_surface_ack_configure(surf, serial);

    /* If the toplevel configure already set a size use it; otherwise fall
     * back to 1024×600 (the known panel size for this hardware). */
    if (!self->m_configured) {
        if (self->m_outputGeometry.isEmpty())
            self->m_outputGeometry = QRect(0, 0, 1024, 600);
        self->m_configured = true;
        WL_INFO << "xdg_surface configured:"
                << self->m_outputGeometry.width() << "x"
                << self->m_outputGeometry.height();
    }

    /* If we have a pending commit (dirty) and no frame callback is armed,
     * now is a good time to commit the first frame. */
    if (self->m_dirty && self->m_pendingCommitSlot >= 0 && !self->m_frameCallback)
        self->doCommit(self->m_pendingCommitSlot);
}

/* -----------------------------------------------------------------------
 * xdg_toplevel configure — compositor tells us the desired size
 * ----------------------------------------------------------------------- */
void QEtnaviv2dWaylandTransport::xdgToplevelConfigure(void *data,
                                                       xdg_toplevel * /*tl*/,
                                                       int32_t w, int32_t h,
                                                       struct wl_array * /*states*/)
{
    auto *self = static_cast<QEtnaviv2dWaylandTransport *>(data);
    /* w==0, h==0 means "compositor doesn't care — use your preferred size" */
    if (w > 0 && h > 0)
        self->m_outputGeometry = QRect(0, 0, w, h);
    WL_DBG << "xdg_toplevel configure: " << w << "x" << h;
}

void QEtnaviv2dWaylandTransport::xdgToplevelClose(void * /*data*/,
                                                   xdg_toplevel * /*tl*/)
{
    WL_INFO << "xdg_toplevel close requested — quitting";
    QCoreApplication::quit();
}

