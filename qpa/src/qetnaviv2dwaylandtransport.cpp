/* -----------------------------------------------------------------------
 * wl_buffer release — slot is free again
 * ----------------------------------------------------------------------- */
void QEtnaviv2dWaylandTransport::bufferRelease(void *data, wl_buffer * /*buf*/)
{
    auto *slot = static_cast<ArgbBo *>(data);
    slot->in_use.store(false);
    WL_DBG << "wl_buffer released — slot back in ring";
}

/* -----------------------------------------------------------------------
 * wl_surface frame callback — vsync tick; commit pending frame if dirty
 * ----------------------------------------------------------------------- */
void QEtnaviv2dWaylandTransport::frameCallback(void *data,
                                                wl_callback *cb,
                                                uint32_t /*time*/)
{
    auto *self = static_cast<QEtnaviv2dWaylandTransport *>(data);

    wl_callback_destroy(cb);
    self->m_frameCallback = nullptr;

    if (self->m_dirty && self->m_pendingCommitSlot >= 0) {
        self->doCommit(self->m_pendingCommitSlot);
    } else {
        /* Nothing to commit this vblank — re-arm so we stay in the chain */
        self->armFrameCallback();
        wl_surface_commit(self->m_surface);
        wl_display_flush(self->m_display);
    }
}

